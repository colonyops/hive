import { chromium, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1280, height: 850 } })
const ssh = ['-i', '/tmp/remote-key', '-o', 'UserKnownHostsFile=/tmp/known_hosts', '-o', 'StrictHostKeyChecking=yes', '-o', 'IdentitiesOnly=yes', '-o', 'BatchMode=yes']
const browserRequests = []
page.on('request', (request) => browserRequests.push(request.url()))
let createdSessionID = ''
try {
  await page.goto('http://127.0.0.1:8080')
  await page.getByTestId('onboarding-hive-skip').click()
  await page.getByTestId('onboarding-permissions-skip').click()
  await page.getByTestId('onboarding-agent-skip').click()
  await page.getByTestId('titlebar-mode-terminal').click()
  await page.getByTestId('terminal-unavailable').waitFor()
  await page.evaluate(() => { location.hash = '/settings/remote' })
  await page.getByTestId('remote-name').fill('Docker Hive')
  await page.getByTestId('remote-color').fill('#a855f7')
  await page.getByTestId('remote-host').fill('hive-fixture')
  await page.getByTestId('remote-connection-file').fill('/home/hive/missing.json')
  await page.getByTestId('remote-connect').click()
  await page.getByTestId('remote-settings-error').filter({ hasText: 'SSH' }).waitFor()
  await page.getByTestId('remote-connection-file').fill('/home/hive/connection.json')
  await page.getByTestId('remote-connect').click()
  await expect(page.getByTestId('remote-code-repo').filter({ hasText: 'repos/demo' }).locator('..')).toHaveCSS('border-left-color', 'rgb(168, 85, 247)')
  await page.getByTestId('remote-code-menu').getByRole('button', { name: /remote-demo/ }).click()
  await page.locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  const input = page.locator('[data-testid="remote-terminal"] .xterm-helper-textarea').first()
  await input.focus()
  const marker = randomUUID()
  await page.keyboard.type(`printf '${marker}\\n' > /home/hive/smoke-result`)
  await page.keyboard.press('Enter')
  await expect.poll(() => execFileSync('ssh', [...ssh, 'hive@remote', 'cat /home/hive/smoke-result'], { encoding: 'utf8' }).trim()).toBe(marker)
  const terminalWidth = () => execFileSync('ssh', [...ssh, 'hive@remote', "tmux display-message -p -t =remote-demo: '#{window_width}'"], { encoding: 'utf8' }).trim()
  const previousWidth = terminalWidth()
  await page.setViewportSize({ width: 1000, height: 700 })
  await expect.poll(terminalWidth).not.toBe(previousWidth)
  await page.getByTestId('remote-code-window').filter({ hasText: 'second' }).click()
  await expect(page.getByTestId('remote-reconnect')).toHaveCount(0)
  await expect(page.getByTestId('remote-pane-statusbar')).toContainText('Docker Hive')
  await expect(page.getByTestId('remote-pane-statusbar').getByTestId('session-status-branch')).toBeVisible()
  await expect(page.getByTestId('remote-pane-statusbar-reveal')).toHaveCount(0)
  execFileSync('pkill', ['-f', '^ssh .* -W '])
  await page.getByTestId('remote-terminal-disconnected').waitFor()
  await page.getByTestId('remote-reconnect').click()
  await page.locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  await expect(page.getByTestId('remote-code-window').filter({ hasText: 'second' })).toHaveClass(/window-row-active/)
  await expect(page.getByTestId('remote-code-menu')).toBeVisible()
  await expect(page.getByTestId('terminal-session-sidebar')).toBeVisible()
  const codeName = `smoke-code-${randomUUID().slice(0, 8)}`
  await page.getByTestId('terminal-new-session').click()
  await page.getByTestId('new-session-repository').click()
  await page.getByTestId('new-session-repository-option').filter({ hasText: 'Docker Hive' }).filter({ hasText: 'repos/demo' }).first().click()
  await page.getByTestId('new-session-name').fill(codeName)
  await page.getByTestId('new-session-submit').click()
  await expect(page.getByTestId('new-session-dialog')).toBeHidden({ timeout: 90000 })
  const codeRow = page.getByTestId('remote-code-menu').getByRole('button', { name: new RegExp(codeName) })
  await expect(codeRow).toBeVisible()
  await codeRow.click()
  await page.locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  const sessionRows = execFileSync('ssh', [...ssh, 'hive@remote', 'hive session list --json'], { encoding: 'utf8' }).trim().split('\n').map(line => JSON.parse(line))
  createdSessionID = sessionRows.find(row => row.name === codeName)?.id
  assert.ok(createdSessionID, 'new session is stored on the remote installation')
  await codeRow.getByTestId('remote-new-window').click()
  await page.getByTestId('new-window-agent-shell').click()
  await expect.poll(() => execFileSync('ssh', [...ssh, 'hive@remote', `tmux list-windows -t =${codeName} -F '#{window_id}'`], { encoding: 'utf8' }).trim().split('\n').length).toBeGreaterThan(2)
  const beforeShortcut = execFileSync('ssh', [...ssh, 'hive@remote', `tmux list-windows -t =${codeName} -F '#{window_id}'`], { encoding: 'utf8' }).trim().split('\n').length
  await page.getByTestId('remote-pane-statusbar').click()
  await page.keyboard.press('Control+t')
  await expect.poll(() => execFileSync('ssh', [...ssh, 'hive@remote', `tmux list-windows -t =${codeName} -F '#{window_id}'`], { encoding: 'utf8' }).trim().split('\n').length).toBe(beforeShortcut + 1)
  await page.getByTestId('titlebar-mode-hub').click()
  const inbox = page.getByTestId('remote-inbox-item-remote-demo')
  await expect(inbox).toHaveCSS('border-left-color', 'rgb(168, 85, 247)')
  await inbox.click()
  await page.getByTestId('remote-inbox').waitFor()
  await page.getByTestId('titlebar-mode-agents').click()
  const workspace = page.getByTestId('remote-chats-item-remote-shell').filter({ visible: true })
  await expect(workspace).toHaveCSS('border-left-color', 'rgb(168, 85, 247)')
  await workspace.click()
  await expect(page.getByTestId('agents-sidebar-tree')).toBeVisible()
  await expect(workspace).toBeVisible()
  await page.getByTestId('remote-chat-name').fill(`Smoke ${marker}`)
  await page.getByTestId('remote-chat-new').click()
  await page.getByTestId('remote-chats').locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  const chatInput = page.locator('[data-testid="remote-chats"] .xterm-helper-textarea').first()
  await chatInput.focus()
  await page.keyboard.type(`printf '${marker}\\n' > /home/hive/chat-smoke-result`)
  await page.keyboard.press('Enter')
  await expect.poll(() => execFileSync('ssh', [...ssh, 'hive@remote', 'cat /home/hive/chat-smoke-result'], { encoding: 'utf8' }).trim()).toBe(marker)
  execFileSync('pkill', ['-f', '^ssh .* -W '])
  await page.getByTestId('remote-chats').getByTestId('remote-terminal-disconnected').waitFor()
  await page.getByTestId('remote-chats').getByTestId('remote-reconnect').click()
  await page.getByTestId('remote-chats').locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  await page.getByTestId('titlebar-mode-terminal').click()
  await page.getByTestId('remote-code').locator('[data-testid="remote-terminal"][data-status="live"]').waitFor()
  await page.getByTestId('remote-open-settings').filter({ visible: true }).click()
  await page.getByTestId('remote-disconnect').click()
  execFileSync('ssh', [...ssh, 'hive@remote', 'tmux has-session -t =remote-demo'])
  assert.ok(browserRequests.every((address) => !address.includes('19001') && !address.includes('hive-remote:')), 'remote traffic stays in Go')
  console.log('PASS: Go-managed SSH/TLS discovery, no browser credentials, remote terminal input, windows, resize, tunnel loss/reconnect detach survival, purple navigation and remote chat creation')
} catch (error) {
  console.error('Page:', await page.locator('body').innerText())
  throw error
} finally {
  if (createdSessionID) execFileSync('ssh', [...ssh, 'hive@remote', `hive session delete ${createdSessionID}`])
  await browser.close()
}
